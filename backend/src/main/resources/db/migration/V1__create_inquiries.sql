-- ---------------------------------------------------------------------------
-- V1: inquiry intake table.
--
-- Design notes
--  * `id`          : internal surrogate key, never exposed through the API.
--  * `public_id`   : opaque UUID returned to the client, used as the reference.
--  * `export_status` + `export_attempts` implement a *transactional outbox*:
--    the row is committed first (durability), the Excel/Sheets export happens
--    asynchronously and is retried by a sweeper until it succeeds. A crash
--    between commit and export therefore never loses data.
--  * `client_request_id` gives the endpoint idempotency so that a double click
--    or a network retry cannot create duplicate rows.
-- ---------------------------------------------------------------------------
CREATE TABLE inquiries
(
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id           UUID         NOT NULL UNIQUE,
    client_request_id   VARCHAR(64)  NOT NULL UNIQUE,
    name                VARCHAR(80)  NOT NULL,
    email               VARCHAR(254) NOT NULL,
    phone               VARCHAR(24)  NOT NULL,
    company             VARCHAR(120),
    message             VARCHAR(2000) NOT NULL,
    consent             BOOLEAN      NOT NULL DEFAULT FALSE,
    export_status       VARCHAR(16)  NOT NULL DEFAULT 'PENDING',
    export_attempts     INTEGER      NOT NULL DEFAULT 0,
    export_error        VARCHAR(400),
    exported_at         TIMESTAMP WITH TIME ZONE,
    source_ip_hash      VARCHAR(64),
    user_agent          VARCHAR(256),
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version             BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT inquiries_export_status_check
        CHECK (export_status IN ('PENDING', 'PROCESSING', 'EXPORTED', 'FAILED'))
);

-- Drives the export sweeper: "give me the oldest still-pending rows".
CREATE INDEX idx_inquiries_export_pending
    ON inquiries (export_status, id);

-- Operational reporting / support lookups.
--
-- `email` is indexed as stored, not as `lower(email)`: InputSanitizer lower-cases every address
-- before it reaches the database, so the two indexes would be equivalent - and the plain column
-- index also keeps the migration portable to test databases that have no expression indexes.
CREATE INDEX idx_inquiries_created_at
    ON inquiries (created_at DESC);

CREATE INDEX idx_inquiries_email
    ON inquiries (email);

COMMENT ON TABLE inquiries IS 'Contact/product inquiries captured from the public landing page.';
COMMENT ON COLUMN inquiries.source_ip_hash IS 'HMAC-SHA256(client IP, APP_HASH_SECRET) - pseudonymous, not reversible by the app.';
